    STREAMWATCH_DB.RAW.DIM_CONTENT AS DIM_CONTENT
LEFT JOIN
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
ON
    FCT_WATCH_EVENTS.CONTENT_KEY = DIM_CONTENT.CONTENT_KEY
GROUP BY
    DIM_CONTENT.CONTENT_TITLE, DIM_CONTENT.CONTENT_KEY, DIM_CONTENT.CONTENT_GENRE
ORDER BY  TOTAL_WATCH_EVENTS DESC;

