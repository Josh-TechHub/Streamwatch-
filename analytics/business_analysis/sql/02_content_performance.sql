-- CONTENT AGE ANALYSIS.
SELECT  --Content age in years.
    CONTENT_ID,
    CONTENT_TITLE,
    FLOOR(MONTHS_BETWEEN(CURRENT_DATE(), CONTENT_RELEASE_DATE) / 12) AS AGE_IN_YEARS
FROM
    STREAMWATCH_DB.RAW.DIM_CONTENT;

SELECT  --Viewing Activity and Completion rate by content age.
    FLOOR(MONTHS_BETWEEN(CURRENT_DATE(), CONTENT_RELEASE_DATE) / 12) AS AGE_IN_YEARS,
    COUNT(FCT_WATCH_EVENTS.EVENT_ID) AS TOTAL_VIEWING_ACTIVITY,
    SUM(FCT_WATCH_EVENTS.COMPLETED_FLAG) / NULLIF(COUNT(FCT_WATCH_EVENTS.EVENT_ID), 0) * 100 AS COMPLETION_RATE
FROM 
    STREAMWATCH_DB.RAW.DIM_CONTENT AS DIM_CONTENT
LEFT JOIN 
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
    ON FCT_WATCH_EVENTS.CONTENT_KEY = DIM_CONTENT.CONTENT_KEY
GROUP BY
    AGE_IN_YEARS
ORDER BY
    COMPLETION_RATE DESC;

--Viewing Activity and Completion rate by Content Age Category.
WITH BANDED_EVENTS AS (
    SELECT 
        CASE 
            WHEN FLOOR(MONTHS_BETWEEN(CURRENT_DATE(), DIM_CONTENT.CONTENT_RELEASE_DATE) / 12) BETWEEN 0 AND 2 THEN '0-2'
            WHEN FLOOR(MONTHS_BETWEEN(CURRENT_DATE(), DIM_CONTENT.CONTENT_RELEASE_DATE) / 12) BETWEEN 3 AND 5 THEN '3-5'
            WHEN FLOOR(MONTHS_BETWEEN(CURRENT_DATE(), DIM_CONTENT.CONTENT_RELEASE_DATE) / 12) BETWEEN 6 AND 8 THEN '6-8'
            WHEN FLOOR(MONTHS_BETWEEN(CURRENT_DATE(), DIM_CONTENT.CONTENT_RELEASE_DATE) / 12) BETWEEN 9 AND 12 THEN '9-12'
            ELSE 'Other' 
        END AS AGE_YEAR_CATEGORY,
        FCT_WATCH_EVENTS.EVENT_ID AS EVENT_ID,
        FCT_WATCH_EVENTS.COMPLETED_FLAG AS COMPLETED_FLAG
    FROM STREAMWATCH_DB.RAW.DIM_CONTENT AS DIM_CONTENT
    LEFT JOIN STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
        ON FCT_WATCH_EVENTS.CONTENT_KEY = DIM_CONTENT.CONTENT_KEY
)
SELECT 
    AGE_YEAR_CATEGORY,
    COUNT(EVENT_ID) AS TOTAL_VIEWING_ACTIVITY,
    ROUND(SUM(COMPLETED_FLAG) / NULLIF(COUNT(EVENT_ID), 0) * 100, 2) AS COMPLETION_RATE
FROM BANDED_EVENTS
GROUP BY AGE_YEAR_CATEGORY
ORDER BY 
    CASE AGE_YEAR_CATEGORY
        WHEN '0-2' THEN 1
        WHEN '3-5' THEN 2
        WHEN '6-8' THEN 3
        WHEN '9-12' THEN 4
        ELSE 5
    END;


