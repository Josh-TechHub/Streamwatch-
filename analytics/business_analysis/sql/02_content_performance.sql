-- Overall performance metrics for each content title.
SELECT
    DIM_CONTENT.CONTENT_KEY AS CONTENT_KEY,
    DIM_CONTENT.CONTENT_TITLE AS CONTENT_TITLE,
    DIM_CONTENT.CONTENT_GENRE AS CONTENT_GENRE,
    NULLIF (COUNT(FCT_WATCH_EVENTS.EVENT_ID), 0) AS TOTAL_WATCH_EVENTS,
    COUNT(DISTINCT FCT_WATCH_EVENTS.USER_KEY) AS UNIQUE_VIEWERS,
    SUM(FCT_WATCH_EVENTS.MINUTES_WATCHED) / 60.0 AS TOTAL_WATCH_TIME,
    SUM(FCT_WATCH_EVENTS.COMPLETED_FLAG) / NULLIF (COUNT(FCT_WATCH_EVENTS.EVENT_ID), 0) * 100 AS COMPLETION_RATE,
    AVG(FCT_WATCH_EVENTS.COMPLETION_PCT) AS AVG_COMPLETION_PCT
