-- Engagemnt Threshold Validation
WITH CTE AS
(
SELECT
    DIM_CONTENT.CONTENT_KEY,
    COUNT(FCT_WATCH_EVENTS.EVENT_ID) AS TOTAL_EVENTS
FROM 
    STREAMWATCH_DB.RAW.DIM_CONTENT AS DIM_CONTENT
LEFT JOIN 
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
    ON FCT_WATCH_EVENTS.CONTENT_KEY = DIM_CONTENT.CONTENT_KEY
GROUP BY
    DIM_CONTENT.CONTENT_KEY
)
SELECT
    COUNT(*) AS TOTAL_TITLE,
    MIN(TOTAL_EVENTS) AS MIN_EVENTS,
    MAX(TOTAL_EVENTS) AS MAX_EVENTS,
    ROUND(AVG(TOTAL_EVENTS), 0) AS AVG_EVENTS,
    MEDIAN(TOTAL_EVENTS) AS MEDIAN_EVENTS
FROM
    CTE;

-- Completion Threshold Validation
WITH CTE AS
(
SELECT 
    DIM_CONTENT.CONTENT_KEY,
    SUM(FCT_WATCH_EVENTS.COMPLETED_FLAG) / NULLIF(COUNT(FCT_WATCH_EVENTS.EVENT_ID), 0) * 100 AS COMPLETION_RATE
FROM STREAMWATCH_DB.RAW.DIM_CONTENT AS DIM_CONTENT
LEFT JOIN 
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
    ON FCT_WATCH_EVENTS.CONTENT_KEY = DIM_CONTENT.CONTENT_KEY
GROUP BY
    DIM_CONTENT.CONTENT_KEY
)
SELECT
    COUNT(*) AS TOTAL_TITLE,
    MIN(COMPLETION_RATE) MIN_COMPLETION_RATE,
    MAX(COMPLETION_RATE) MAX_COMPLETION_RATE,
    ROUND(AVG(COMPLETION_RATE)) AVG_COMPLETION_RATE,
    MEDIAN(COMPLETION_RATE) AS MEDIAN_COMPLETION_RATE
FROM
    CTE;


