DESC TABLE STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS;
DESC TABLE STREAMWATCH_DB.RAW.DIM_USERS;

-- Define engagement metrics and aggregation grain; identify required fact/dimension columns.
SELECT 
    DIM_USERS.USER_KEY,
    DIM_USERS.USER_ID,
    DIM_USERS.USER_COUNTRY,
    DIM_USERS.USER_SUBSCRIPTION_TIER,
    COUNT(FCT_WATCH_EVENTS.EVENT_ID) AS TOTAL_WATCH_EVENTS,
    COALESCE(SUM(MINUTES_WATCHED), 0) / 60.0 AS TOTAL_WATCH_HOURS,
    AVG(MINUTES_WATCHED) AS AVG_MINUTES_WATCHED,
    MEDIAN(MINUTES_WATCHED) AS MEDIAN_MINUTES_WATCHED
FROM
    STREAMWATCH_DB.RAW.DIM_USERS AS DIM_USERS
LEFT JOIN
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
ON
    FCT_WATCH_EVENTS.USER_KEY = DIM_USERS.USER_KEY
GROUP BY
    DIM_USERS.USER_KEY,
    DIM_USERS.USER_ID,
    DIM_USERS.USER_COUNTRY,
    DIM_USERS.USER_SUBSCRIPTION_TIER;
--
SELECT 
    COUNT(DISTINCT DIM_USERS.USER_KEY) AS TOTAL_USERS,
    COUNT(DISTINCT FCT_WATCH_EVENTS.USER_KEY) AS USERS_WITH_ACTIVITY,
    COUNT(DISTINCT DIM_USERS.USER_KEY) - COUNT(DISTINCT FCT_WATCH_EVENTS.USER_KEY) AS USERS_WITHOUT_ACTIVITY
FROM
    STREAMWATCH_DB.RAW.DIM_USERS AS DIM_USERS
LEFT JOIN
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
ON
    FCT_WATCH_EVENTS.USER_KEY = DIM_USERS.USER_KEY;

--Event engagement metrics
SELECT
    COUNT(*) TOTAL_WATCH_EVENTS,
    SUM(MINUTES_WATCHED) / 60.0 AS TOTAL_HOURS_WATCHED,
    AVG(MINUTES_WATCHED) AS AVG_VIEWING_DURATION,
    MEDIAN(MINUTES_WATCHED) AS MEDIAN_VIEWING_DURATION
FROM
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS;

--User engagement metrics
SELECT
    DIM_USERS.USER_KEY,
    DIM_USERS.USER_ID AS USER_ID,
    COUNT(FCT_WATCH_EVENTS.EVENT_ID) AS TOTAL_WATCH_EVENTS,
    SUM(FCT_WATCH_EVENTS.MINUTES_WATCHED) / 60.0 AS TOTAL_WATCH_TIME,
    AVG(FCT_WATCH_EVENTS.MINUTES_WATCHED) /60.0 AS AVG_WATCH_TIME,
    MEDIAN(FCT_WATCH_EVENTS.MINUTES_WATCHED) /60.0 AS MEDIAN_WATCH_TIME
FROM
    STREAMWATCH_DB.RAW.DIM_USERS AS DIM_USERS
LEFT JOIN
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
ON
    FCT_WATCH_EVENTS.USER_KEY = DIM_USERS.USER_KEY
GROUP BY
    DIM_USERS.USER_KEY, DIM_USERS.USER_ID;



