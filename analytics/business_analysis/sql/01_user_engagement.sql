    DIM_USERS.USER_KEY, DIM_USERS.USER_ID
)
SELECT
     USER_ID,
     TOTAL_WATCH_EVENTS,
     TOTAL_WATCH_TIME,
     AVG_WATCH_TIME,
     MEDIAN_WATCH_TIME,
     AVG(TOTAL_WATCH_TIME) OVER() AS AVG_TOTAL_WATCH_TIME,
     MEDIAN(TOTAL_WATCH_TIME) OVER() AS MEDIAN_TOTAL_WATCH_TIME
FROM
    USERS_ENGAGEMENT_METRICS;

