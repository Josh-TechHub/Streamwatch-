    DIM_USERS.USER_KEY,
    DIM_USERS.USER_ID AS USER_ID,
    COUNT(FCT_WATCH_EVENTS.EVENT_ID) AS TOTAL_WATCH_EVENTS,
    SUM(FCT_WATCH_EVENTS.MINUTES_WATCHED) / 60.0 AS TOTAL_WATCH_TIME,
    AVG(FCT_WATCH_EVENTS.MINUTES_WATCHED) /60.0 AS AVG_WATCH_TIME,
    MEDIAN(FCT_WATCH_EVENTS.MINUTES_WATCHED) /60.0 AS MEDIAN_WATCH_TIME
