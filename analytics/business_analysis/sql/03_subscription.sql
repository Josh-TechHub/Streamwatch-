SELECT 
    DIM_USER.USER_SUBSCRIPTION_TIER,
    FCT_WATCH_EVENT.WATCH_DATE
FROM
    STREAMWATCH_DB.RAW.DIM_USERS AS DIM_USERS
LEFT JOIN
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
    ON DIM_USERS.USER_KEY = FCT_WATCH_EVENTS.USER_KEY
ORDER BY
    FCT_WATCH_EVENT.WATCH_DATE;


-- USER-SUBSCRIPTION DISTRIBUTION
SELECT
    USER_SUBSCRIPTION_TIER,
    COUNT(USER_ID) AS TOTAL_USERS,
    ROUND(COUNT(USER_ID) * 100.0 / SUM(COUNT(USER_ID)) OVER (),2) AS USER_PERCENTAGE
FROM STREAMWATCH_DB.RAW.DIM_USERS
GROUP BY
    USER_SUBSCRIPTION_TIER
ORDER BY
    TOTAL_USERS DESC;

--Viewing activity by subscription tier
SELECT
    DIM_USERS.USER_SUBSCRIPTION_TIER,
    COUNT(FCT_WATCH_EVENTS.EVENT_ID) AS TOTAL_VIEWING_EVENTS,
    COUNT(DISTINCT FCT_WATCH_EVENTS.USER_KEY) AS UNIQUE_VIEWERS,
    ROUND(
        COUNT(FCT_WATCH_EVENTS.EVENT_ID) * 1.0 /
        NULLIF(COUNT(DISTINCT FCT_WATCH_EVENTS.USER_KEY), 0),
        2
    ) AS AVG_EVENTS_PER_VIEWER,
    ROUND(
        SUM(FCT_WATCH_EVENTS.MINUTES_WATCHED) / 60.0,
        2
    ) AS TOTAL_WATCH_HOURS
FROM STREAMWATCH_DB.RAW.DIM_USERS AS DIM_USERS
INNER JOIN STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
    ON DIM_USERS.USER_KEY = FCT_WATCH_EVENTS.USER_KEY
GROUP BY
    DIM_USERS.USER_SUBSCRIPTION_TIER
ORDER BY
    TOTAL_VIEWING_EVENTS DESC;
    

SELECT
    DIM_USERS.USER_SUBSCRIPTION_TIER,

    ROUND(
        AVG(FCT_WATCH_EVENTS.MINUTES_WATCHED),
        2
    ) AS AVG_MINUTES_PER_EVENT,

    ROUND(
        SUM(FCT_WATCH_EVENTS.MINUTES_WATCHED) / 60.0 /
        NULLIF(COUNT(DISTINCT FCT_WATCH_EVENTS.USER_KEY), 0),
        2
    ) AS AVG_WATCH_HOURS_PER_VIEWER

FROM STREAMWATCH_DB.RAW.DIM_USERS AS DIM_USERS

INNER JOIN STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS AS FCT_WATCH_EVENTS
    ON DIM_USERS.USER_KEY = FCT_WATCH_EVENTS.USER_KEY

GROUP BY
    DIM_USERS.USER_SUBSCRIPTION_TIER

ORDER BY
    DIM_USERS.USER_SUBSCRIPTION_TIER DESC;