-- USER-DIVICE DISTRIBUTION

--Viewing activity by device type
SELECT
    DEVICE_TYPE,
    COUNT(EVENT_ID) AS TOTAL_VIEWING_EVENTS,
    COUNT(DISTINCT USER_KEY) AS UNIQUE_VIEWERS,

    ROUND(
        COUNT(EVENT_ID) * 100.0 /
        SUM(COUNT(EVENT_ID)) OVER (),
        2
    ) AS VIEWING_ACTIVITY_PERCENTAGE,

    SUM(COMPLETED_FLAG) AS COMPLETED_EVENTS,

    ROUND(
        SUM(COMPLETED_FLAG) * 100.0 /
        NULLIF(COUNT(EVENT_ID), 0),
        2
    ) AS COMPLETION_RATE

FROM STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS

GROUP BY DEVICE_TYPE

ORDER BY TOTAL_VIEWING_EVENTS DESC;



-- Multi-Device Usage Analysis
WITH USER_DEVICE_COUNT AS
(
    SELECT
        USER_KEY,
        COUNT(DISTINCT DEVICE_TYPE) AS TOTAL_DEVICES_USED
    FROM STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
    GROUP BY USER_KEY
)

SELECT
    TOTAL_DEVICES_USED,
    COUNT(USER_KEY) AS TOTAL_USERS,
    ROUND(
        COUNT(USER_KEY) * 100.0 /
        SUM(COUNT(USER_KEY)) OVER (),
        2
    ) AS USER_PERCENTAGE
FROM USER_DEVICE_COUNT
GROUP BY TOTAL_DEVICES_USED
ORDER BY TOTAL_DEVICES_USED;

