-- USER REFERENTIAL INTEGRITY CHECK

SELECT 
    FCT_WATCH_EVENTS.USER_ID,
    DIM_USERS.USER_ID
FROM FCT_WATCH_EVENTS
LEFT JOIN DIM_USERS
    ON FCT_WATCH_EVENTS.USER_ID = DIM_USERS.USER_ID
WHERE DIM_USERS.USER_ID IS NULL;

-- CONTENT REFERENTIAL INTEGRITY CHECK
SELECT 
    FCT_WATCH_EVENTS.CONTENT_ID,
    DIM_CONTENT.CONTENT_ID
FROM FCT_WATCH_EVENTS
LEFT JOIN DIM_CONTENT
    ON FCT_WATCH_EVENTS.CONTENT_ID = DIM_CONTENT.CONTENT_ID
WHERE DIM_CONTENT.CONTENT_ID IS NULL;