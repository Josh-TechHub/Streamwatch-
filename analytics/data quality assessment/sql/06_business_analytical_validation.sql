---
SELECT 
    COMPLETED_FLAG,
    AVG(COMPLETION_PCT) AS AVG_COMPLETION_PCT,
    MIN(COMPLETION_PCT) AS MIN_COMPLETION_PCT,
    MAX(COMPLETION_PCT) AS MAX_COMPLETION_PCT
FROM 
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
GROUP BY 
    COMPLETED_FLAG;

SELECT 
    COMPLETED_FLAG,
    CASE 
        WHEN COMPLETION_PCT < 80 THEN 'Below 80'
        WHEN COMPLETION_PCT >= 80 AND COMPLETION_PCT <= 84.99 THEN '80-84.99'
        WHEN COMPLETION_PCT >= 85 AND COMPLETION_PCT <= 89.99 THEN '85-89.99'
        WHEN COMPLETION_PCT >= 90 AND COMPLETION_PCT <= 94.99 THEN '90-94.99'
        WHEN COMPLETION_PCT >= 95 AND COMPLETION_PCT <= 99.99 THEN '95-99.99'
        WHEN COMPLETION_PCT > 99.99 THEN '100'
        ELSE 'Other'
    END AS COMPLETION_PCT_RANGE,
    COUNT(*) AS EVENT_COUNT
FROM 
    STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
GROUP BY 
    COMPLETED_FLAG,
    COMPLETION_PCT_RANGE 
ORDER BY
    COMPLETION_PCT_RANGE ASC;

