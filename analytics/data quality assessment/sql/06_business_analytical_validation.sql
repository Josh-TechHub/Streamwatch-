-- Compare viewing duration with content duration; check COMPLETION_PCT against COMPLETED_FLAG.
DESC TABLE IDENTIFIER ('STREAMWATCH_DB.RAW.DIM_CONTENT');
DESC TABLE IDENTIFIER('STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS');

SELECT
    COUNT(*),
    CASE 
        WHEN FCT_WATCH_EVENTS.MINUTES_WATCHED < DIM_CONTENT.CONTENT_DURATION_MINUTES THEN 'Below'
        WHEN FCT_WATCH_EVENTS.MINUTES_WATCHED = DIM_CONTENT.CONTENT_DURATION_MINUTES THEN 'Equal'
        WHEN FCT_WATCH_EVENTS.MINUTES_WATCHED > DIM_CONTENT.CONTENT_DURATION_MINUTES THEN 'Above' 
    END AS COMPARISON
FROM STREAMWATCH_DB.RAW.DIM_CONTENT
LEFT JOIN STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
    ON DIM_CONTENT.CONTENT_KEY = FCT_WATCH_EVENTS.CONTENT_KEY
GROUP BY
    COMPARISON;
--check COMPLETION_PCT against COMPLETED_FLAG.
SELECT 
    COUNT(*)
FROM 
STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
WHERE 
    COMPLETED_FLAG = 1;
---
SELECT 
    COUNT(*)
FROM 
STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
WHERE 
