-- FCT_WATCH_EVENTS
SELECT 
    EVENT_ID
FROM STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
GROUP BY EVENT_ID
HAVING COUNT(*) > 1;

SELECT 
    WATCH_EVENT_KEY
FROM STREAMWATCH_DB.RAW.FCT_WATCH_EVENTS
GROUP BY WATCH_EVENT_KEY
HAVING COUNT(*) > 1;



-- DIM_USER
SELECT 
    USER_KEY
FROM STREAMWATCH_DB.RAW.DIM_USERS
GROUP BY USER_KEY
HAVING COUNT(*) > 1;

SELECT
    USER_ID
FROM STREAMWATCH_DB.RAW.DIM_USERS
GROUP BY USER_ID
HAVING COUNT(*) > 1;



-- DIM_CONTENT
SELECT
    CONTENT_KEY
FROM STREAMWATCH_DB.RAW.DIM_CONTENT
GROUP BY CONTENT_KEY
HAVING COUNT(*) > 1;

SELECT 
    CONTENT_ID
FROM STREAMWATCH_DB.RAW.DIM_CONTENT
GROUP BY CONTENT_ID
HAVING COUNT(*) > 1;